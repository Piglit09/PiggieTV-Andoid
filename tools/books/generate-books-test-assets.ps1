    ".\tools\books\generate-books-test-assets.ps1",
    '```'
) -join "`n"
Write-GeneratedText -Path (Join-Path $booksRoot "README.md") -Content $readmeContent

$outputs = New-Object System.Collections.Generic.List[string]

