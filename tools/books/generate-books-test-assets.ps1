    $paragraphs = for ($index = 1; $index -le $ParagraphCount; $index++) {
        "Paragraph $index. This generated PiggieTV Books validation text exercises native TXT pagination, resume, settings persistence, and long-document scrolling."
    }
    Write-GeneratedText -Path $Path -Content @"
$GeneratedMarker

$Title

$($paragraphs -join "`n`n")
"@
}

