    @Test
    fun `cold Auto queue uses freshly fetched genre ID to retrieve seed matched songs`() = runBlocking<Unit> {
        val client = RecommendationApiClient()
        val repository = MusicRepository(client, savedUserIdProvider = { USER_ID })

        val queue = repository.loadAutoGeneratedQueue(seed = seed())

        client.itemQueries.any { query -> query["genreIds"] == listOf(METAL_GENRE_ID) } shouldBe true
        queue.map(MusicItem::id) shouldContain METAL_TRACK_ID
    }

    @Test
    fun `not interested feedback stays with its server and user after account switches`() {
        val context = mockk<Context>()
        val preferences = mockk<SharedPreferences>()
        val editor = mockk<SharedPreferences.Editor>()
        val stored = mutableMapOf<String, MutableSet<String>>()
        every { context.applicationContext } returns context
        every { context.getSharedPreferences(any(), Context.MODE_PRIVATE) } returns preferences
        every { preferences.getStringSet(any(), any()) } answers { stored[firstArg<String>()] ?: mutableSetOf() }
        every { preferences.edit() } returns editor
        every { editor.putStringSet(any(), any()) } answers {
            stored[firstArg<String>()] = secondArg<Set<String>>().toMutableSet()
            editor
        }
        every { editor.apply() } returns Unit
        stored["not_interested_item_ids"] = mutableSetOf(SEED_ID.toString())
        var selectedUser = USER_ID
        val repository = MusicRepository(
            apiClient = RecommendationApiClient(),
            context = context,
            savedUserIdProvider = { selectedUser },
        )

        repository.notInterestedItemIds() shouldBe emptySet()
        repository.toggleNotInterested(seed()) shouldBe true
        selectedUser = OTHER_USER_ID
        repository.notInterestedItemIds() shouldBe emptySet()
        repository.toggleNotInterested(seed().copy(id = METAL_TRACK_ID)) shouldBe true
        selectedUser = USER_ID
        repository.notInterestedItemIds() shouldBe setOf(SEED_ID)

        val sameAccount = MusicRepository(
            apiClient = RecommendationApiClient(),
            context = context,
            savedUserIdProvider = { USER_ID },
        )
        sameAccount.notInterestedItemIds() shouldBe setOf(SEED_ID)

        val otherServer = MusicRepository(
            apiClient = RecommendationApiClient(serverUrl = "https://other-jellyfin.example.invalid"),
            context = context,
            savedUserIdProvider = { USER_ID },
        )
        otherServer.notInterestedItemIds() shouldBe emptySet()
    }

