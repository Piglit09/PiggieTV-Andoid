    @Test
    fun `Auto session replenishes across 100 transitions without repeating skipped songs`() = runBlocking<Unit> {
        val client = RecommendationApiClient(sessionCatalogSize = 220)
        val repository = MusicRepository(client, savedUserIdProvider = { USER_ID })
        val seed = seed()
        var session = repository.beginAutoRecommendationSession(
            seed = seed,
            initialQueue = listOf(seed),
            mode = MusicListeningMode.BALANCED_DISCOVERY,
        )
        var currentItem = seed
        val queuedIds = mutableSetOf(seed.id)
        val skippedIds = mutableSetOf<UUID>()
        val futureSkippedId = UUID(3L, 5L)
        skippedIds += futureSkippedId
        session = session.recordSkipped(futureSkippedId)

        repeat(6) { refillIndex ->
            val batch = repository.replenishAutoRecommendations(
                context = session,
                currentItem = currentItem,
                limit = 20,
            )
            batch.items.size shouldBe 20
            batch.items.all { item -> item.id !in queuedIds && item.id !in skippedIds } shouldBe true
            session = batch.context
            batch.items.forEachIndexed { index, item ->
                queuedIds += item.id
                session = if ((refillIndex * 20 + index + 1) % 11 == 0) {
                    skippedIds += item.id
                    session.recordSkipped(item.id)
                } else {
                    currentItem = item
                    session.recordPlayed(item)
                }
            }
        }

        queuedIds.size shouldBe 121
        session.selectedMode shouldBe MusicListeningMode.BALANCED_DISCOVERY
        session.skippedIds.containsAll(skippedIds) shouldBe true
        (session.recentPlayedIds.size <= 32) shouldBe true
        (session.skippedIds.size <= 64) shouldBe true
        (session.recommendedIds.size <= 512) shouldBe true
        val uniqueStartIndices = client.itemQueries.mapNotNull { query -> query["startIndex"] as? Int }.distinct()
        (uniqueStartIndices.size >= 6) shouldBe true
    }

    @Test
    fun `Auto recommendation session rejects a different account before returning candidates`() = runBlocking<Unit> {
        var selectedUser = USER_ID
        val client = RecommendationApiClient(sessionCatalogSize = 100)
        val repository = MusicRepository(client, savedUserIdProvider = { selectedUser })
        val session = repository.beginAutoRecommendationSession(
            seed = seed(),
            initialQueue = listOf(seed()),
            mode = MusicListeningMode.STAY_IN_THE_VIBE,
        )

        val staleSelection = runCatching {
            repository.replenishAutoRecommendations(
                context = session,
                currentItem = seed().copy(id = METAL_TRACK_ID),
                limit = 20,
            )
        }.exceptionOrNull()
        (staleSelection is IllegalStateException) shouldBe true
        client.itemQueries shouldBe emptyList()

        selectedUser = OTHER_USER_ID
        val failure = runCatching {
            repository.replenishAutoRecommendations(context = session, currentItem = seed(), limit = 20)
        }.exceptionOrNull()

        (failure is IllegalStateException) shouldBe true
        client.itemQueries shouldBe emptyList()
    }

    @Test
    fun `Auto recommendation session ends safely when no unseen catalog songs remain`() = runBlocking<Unit> {
        val repository = MusicRepository(
            apiClient = RecommendationApiClient(sessionCatalogSize = 2),
            savedUserIdProvider = { USER_ID },
        )
        val seed = seed()
        val session = repository.beginAutoRecommendationSession(
            seed = seed,
            initialQueue = listOf(seed),
            mode = MusicListeningMode.ANYTHING_GOES,
        )

        val first = repository.replenishAutoRecommendations(context = session, currentItem = seed, limit = 20)
        first.items.size shouldBe 2
        val exhausted = repository.replenishAutoRecommendations(
            context = first.context,
            currentItem = first.items.last(),
            limit = 20,
        )
        exhausted.items shouldBe emptyList()
        exhausted.context.selectedMode shouldBe MusicListeningMode.ANYTHING_GOES
    }

    private class RecommendationApiClient(
        private val serverUrl: String = "https://jellyfin.example.invalid",
        private val modeFixture: Boolean = false,
        private val sessionCatalogSize: Int = 0,
    ) : ApiClient() {
        val itemQueries = CopyOnWriteArrayList<Map<String, Any?>>()

        override val baseUrl: String = serverUrl
        override val accessToken: String = "test-token"
        override val clientInfo: ClientInfo = ClientInfo(name = "test", version = "1")
        override val deviceInfo: DeviceInfo = DeviceInfo(id = "test-device", name = "test")
        override val httpClientOptions: HttpClientOptions = HttpClientOptions()
        override val webSocket: SocketApi = object : SocketApi {
            override val state = MutableStateFlow<SocketApiState>(SocketApiState.Disconnected())

            override fun subscribeAll(): Flow<OutboundWebSocketMessage> = emptyFlow()
            override fun <T : OutboundWebSocketMessage> subscribe(messageType: KClass<T>): Flow<T> = emptyFlow()
        }

        override fun update(baseUrl: String?, accessToken: String?, clientInfo: ClientInfo, deviceInfo: DeviceInfo) =
            Unit

        override suspend fun request(
            method: HttpMethod,
            pathTemplate: String,
            pathParameters: Map<String, Any?>,
            queryParameters: Map<String, Any?>,
            requestBody: Any?,
        ): RawResponse = when (val path = "${method.name} $pathTemplate") {
            "GET /Genres" -> jsonResponse(
                """{"Items":[{"Id":"$METAL_GENRE_ID","Name":"Metal","Type":"Genre"}],"TotalRecordCount":1,"StartIndex":0}""",
            )

            "GET /Items" -> {
                itemQueries += queryParameters
                if (sessionCatalogSize > 0) {
                    val startIndex = (queryParameters["startIndex"] as? Number)?.toInt() ?: 0
                    val limit = (queryParameters["limit"] as? Number)?.toInt() ?: 25
                    val lastIndex = (startIndex + limit).coerceAtMost(sessionCatalogSize)
                    val page = (startIndex until lastIndex).joinToString(",") { index ->
                        audioItemJson(UUID(3L, index.toLong() + 1), if (index % 4 == 0) "Pop" else "Metal")
                    }
                    jsonResponse(
                        """{"Items":[$page],"TotalRecordCount":$sessionCatalogSize,"StartIndex":$startIndex}""",
                    )
                } else {
                    val items = when {
                        queryParameters["genreIds"] == listOf(METAL_GENRE_ID) && modeFixture ->
                            (1..18).joinToString(",") { index ->
                                audioItemJson(UUID(1L, index.toLong()), "Metal")
                            }

                        queryParameters["genreIds"] == listOf(METAL_GENRE_ID) ->
                            audioItemJson(METAL_TRACK_ID, "Metal")

                        queryParameters["isFavorite"] == true && modeFixture ->
                            (1..6).joinToString(",") { index ->
                                audioItemJson(UUID(2L, index.toLong()), "Pop")
                            }

                        else -> ""
                    }
                    val count = if (items.isEmpty()) 0 else items.count { char -> char == '{' }
                    jsonResponse("""{"Items":[$items],"TotalRecordCount":$count,"StartIndex":0}""")
                }
            }

            else -> if (path.contains("Views")) {
                jsonResponse("""{"Items":[],"TotalRecordCount":0,"StartIndex":0}""")
            } else {
                error("Unexpected request $path")
            }
        }

        private fun jsonResponse(json: String) = RawResponse(
            body = json.encodeToByteArray(),
            status = 200,
            headers = emptyMap(),
        )

        private fun audioItemJson(id: UUID, genre: String): String =
            """{"Id":"$id","Name":"$genre song $id","Type":"Audio","MediaType":"Audio","Genres":["$genre"],"IsFolder":false}"""
    }

    private fun seed() = MusicItem(
        id = SEED_ID,
        title = "Slipknot seed",
        subtitle = null,
        album = null,
        albumId = null,
        artist = null,
        artistIds = emptyList(),
        genres = listOf("Metal"),
        type = BaseItemKind.AUDIO,
        collectionType = null,
        posterUrl = null,
        backdropUrl = null,
        container = "mp3",
        codec = "mp3",
        playCount = 0,
        progress = null,
        isFavorite = false,
        isFolder = false,
        isPlayable = true,
    )

    private companion object {
        val USER_ID: UUID = UUID.fromString("00000000-0000-0000-0000-000000000001")
        val OTHER_USER_ID: UUID = UUID.fromString("00000000-0000-0000-0000-000000000002")
        val SEED_ID: UUID = UUID.fromString("11111111-1111-1111-1111-111111111111")
        val METAL_GENRE_ID: UUID = UUID.fromString("22222222-2222-2222-2222-222222222222")
        val METAL_TRACK_ID: UUID = UUID.fromString("33333333-3333-3333-3333-333333333333")
    }
